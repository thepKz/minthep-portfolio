#!/usr/bin/env bash
#
# tools/gen-lqip.sh — emit css/lqip.css from LOCAL repo images.
#
# For each slot it produces two custom properties on :root
#
#     --lqip-<slot>   a 20px-wide WebP inlined as a data: URI (~190 base64 chars)
#     --tint-<slot>   the single dominant colour of the image, as #rrggbb
#
# The data URI is small enough to live in the critical CSS with no extra request,
# so a blur-up placeholder paints on first paint and the real image cross-fades
# in. --tint-* is the no-image fallback and the colour to letterbox against.
#
# NOT a build step — run it locally, commit css/lqip.css.
# Requires: ImageMagick 7 (`magick`), base64.
#
# Usage:  bash tools/gen-lqip.sh [repo-root] > css/lqip.css
#         bash tools/gen-lqip.sh [repo-root] slots.tsv > css/lqip.css
#
#         slots.tsv format:  <slot-name><TAB><repo-relative image path>
#
set -uo pipefail

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
SLOTFILE="${2:-}"
cd "$ROOT" || { echo "cannot cd $ROOT" >&2; exit 1; }

command -v magick >/dev/null 2>&1 || { echo "missing tool: magick" >&2; exit 1; }

TMP="$(mktemp -d -t t06lqip)"
trap 'rm -rf "$TMP"' EXIT

# Default slot table. Every image here is an LCP candidate or an above-the-fold
# card thumbnail on one of the three surfaces — nothing below the fold needs LQIP.
default_slots() {
  cat <<'SLOTS'
conga	img/conga.jpg
project1	img/project1.png
project2	img/project2.png
project3	img/project3.png
project4	img/project4.png
project5	img/project5.png
project6	img/project6.png
genkikoi	img/genkikoi.png
trustfundme	img/trustfundme.png
blackhole	img/blackhole.png
wygallery	img/wygallery.png
welcome	blog/myblog/welcome.png
jpd113	blog/myblog/jpd113.png
jpd123	blog/myblog/jpd123.png
wonyoung	img/wonyoung.jpg
SLOTS
}

emit() {
  echo "/* AUTO-GENERATED by tools/gen-lqip.sh — do not edit. See tools/asset-manifest.json. */"
  echo ":root {"

  while IFS=$'\t' read -r slot path; do
    [ -z "${slot:-}" ] && continue
    case "$slot" in \#*) continue ;; esac
    if [ ! -e "$path" ]; then
      printf '  /* MISSING: %s -> %s */\n' "$slot" "$path"
      continue
    fi

    # 20px wide, profile+metadata stripped => ~120-160 bytes
    magick "$path[0]" -resize 20x -strip -quality 40 "$TMP/x.webp" </dev/null >/dev/null 2>&1 \
      || { printf '  /* FAILED: %s */\n' "$slot"; continue; }

    b64="$(base64 < "$TMP/x.webp" | tr -d '\n')"
    hex="$(magick "$path[0]" -resize 1x1! -alpha off -format '%[hex:p{0,0}]' info: </dev/null 2>/dev/null | tr -d '\n' | cut -c1-6)"
    [ -n "$hex" ] || hex="0E0E10"

    printf '  --lqip-%s: url("data:image/webp;base64,%s");\n' "$slot" "$b64"
    printf '  --tint-%s: #%s;\n' "$slot" "$hex"
  done

  echo "}"
  cat <<'TAIL'
/* <div class="lqip" style="--lqip:var(--lqip-project1);--tint:var(--tint-project1)">
     <picture>…<img … onload="this.parentNode.parentNode.dataset.loaded=1"></picture> */
.lqip{background:var(--tint,#0e0e10) var(--lqip) 50%/cover no-repeat}
.lqip>picture>img,.lqip>img{display:block;width:100%;height:auto}
.lqip[data-loaded]{background-image:none}
@media (prefers-reduced-motion:no-preference){
.lqip>picture>img,.lqip>img{animation:lqip-fade .32s ease-out both}
@keyframes lqip-fade{from{opacity:0}to{opacity:1}}}
TAIL
}

if [ -n "$SLOTFILE" ] && [ -e "$SLOTFILE" ]; then
  emit < "$SLOTFILE"
else
  default_slots | emit
fi
